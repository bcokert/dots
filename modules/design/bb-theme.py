#!/usr/bin/env python3
"""Write Clarity's bb theme: one CSS file with the display and mono fonts inlined, tokens.css, then bb-theme.css.

    python3 modules/design/bb-theme.py modules/bb/plugins/clarity-theme/themes/clarity.css

Run from dots. Re-run after changing tokens.css, bb-theme.css or the
fonts. Inter is left out: bb bundles it. bb caps a theme at ~256 KB, so this refuses to write anything bigger."""
import base64, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
LIMIT = 250 * 1024

def font_faces():
    css = open(os.path.join(here, "fonts", "fonts.css")).read()
    faces = [f for f in re.findall(r"@font-face \{[^}]+\}", css) if '"Inter"' not in f]
    def inline(m):
        data = open(os.path.join(here, "fonts", m.group(1)), "rb").read()
        return 'url("data:font/woff2;base64,%s")' % base64.b64encode(data).decode()
    return "\n".join(re.sub(r'url\("([^"]+\.woff2)"\)', inline, f) for f in faces)

parts = [
    "/* Clarity bb theme. Generated by dots modules/design/bb-theme.py from tokens.css, bb-theme.css and fonts/:\n"
    "   edit those, then re-run it. Fonts: OFL (Chakra Petch, JetBrains Mono). */",
    font_faces(),
    open(os.path.join(here, "tokens.css")).read(),
    open(os.path.join(here, "bb-theme.css")).read(),
]
css = "\n\n".join(parts)
if len(css.encode()) > LIMIT:
    sys.exit("bb-theme.py: %d KB is over bb's theme limit" % (len(css.encode()) // 1024))
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
open(out, "w").write(css)
print(out, len(css.encode()) // 1024, "KB")
